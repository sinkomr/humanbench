/**
 * The local database behind `npm run e2e:db` (ROADMAP M3.11 phase 1, M2.0): a throw-away PostgreSQL
 * cluster with the Supabase shim and `supabase/migrations` (the harness of `npm run test:db`), two
 * databases in it, and an HTTP stand-in for PostgREST in front of each that a browser can call (the
 * one of `scripts/db/postgrest-shim.ts`, plus CORS). Run by the Playwright config as a web server:
 *
 *   npx tsx e2e-db/server.ts
 *
 *   E2E_DB_PORT      "plain":   the pool of the live project in kind, with no text item (default 4188)
 *   E2E_DB_PORT + 1  "text":    the same plus made-up text questions for three of the five text skills
 *   E2E_DB_PORT + 3  "passage": the plain pool plus made-up passages with their questions (M3.11 phase 2)
 *   E2E_DB_PORT + 4  "games":   the plain pool plus made-up logic games (the remaining families, 2026-10-13)
 *   E2E_DB_PORT + 5  "estimates": the plain pool plus made-up Fermi estimates, emotion vignettes, situational
 *                    judgments and word-links puzzles (`scripts/db/families-fixture.ts`)
 *
 * Everything in the pools is made up at start (`scripts/db/bank-fixture.ts` `textItems` and `passageItems`: text
 * that says it is a placeholder, keys drawn by a PRNG) or generated by the app's own procedural family (the series
 * items, whose keys anybody can compute, ROADMAP A1). No real item and no real key is here or anywhere in
 * this repository. Nothing listens beyond 127.0.0.1, and Ctrl-C deletes the data.
 *
 * Three settings of the test databases differ from a deployed project, because a test clicks faster than
 * a person reads and three browsers share one address: the sessions an address may start in a day, the
 * check of the average time per answer, and the exposure cap. And before each answer is stored the
 * server's record of when the question was served is moved back 20 seconds, as the database tests do
 * (`ageExposures`): the scores of a session answered in two seconds a question are withheld by design.
 */

import { createServer, type IncomingMessage, type ServerResponse } from 'node:http'
import { getFamily } from '../src/tasks/registry'
import { loadFixtureBank, passageItems, textItems, type FixtureItem } from '../scripts/db/bank-fixture'
import { startCluster } from '../scripts/db/engine'
import { ANON, createTestDb, type TestDb } from '../scripts/db/harness'
import { statusOf } from '../scripts/db/postgrest-shim'
import { fermiItems, logicGameItems, ratItems, sjtItems, vignetteItems } from '../scripts/db/families-fixture'
import { DB_PORT, ESTIMATES_PORT_OFFSET, FAMILY_ITEMS, GAMES, GAMES_PORT_OFFSET, PASSAGES, PASSAGE_PORT_OFFSET, TEXT_PER_AXIS, TEXT_PRESENT, passageCredit } from './pool'


const CORS = { 'access-control-allow-origin': '*', 'access-control-allow-headers': '*', 'access-control-allow-methods': 'POST, OPTIONS', 'access-control-max-age': '600' }

/** Series items the app can draw and the server can score: the generator's own instances, stored as the bank stores them. */
function seriesItems(n: number): FixtureItem[] {
  const family = getFamily('series')!
  return Array.from({ length: n }, (_, i): FixtureItem => {
    const it = family.generate(`e2edb${i}`)
    const p = it.params as { a: number; b: number }
    return {
      itemId: it.item_id,
      familyId: it.family_id,
      siblingGroup: it.sibling_group,
      axis: 'MAT',
      facet: 'series',
      itemType: 'numeric',
      model: '2pl',
      a: p.a,
      b: p.b,
      c: null,
      nOptions: 0,
      key: it.key as Record<string, unknown>,
      status: 'live',
      practiceOnly: false,
      generator: 'series',
      procedural: true,
      expectedTimeS: 30,
      payload: { media: { renderer: 'series', ...(it.spec as object) } },
    }
  })
}

async function relax(db: TestDb): Promise<void> {
  const values: [string, number][] = [['rate.sessions_per_day', 100000], ['session.min_avg_ms', 0], ['selection.exposure_cap', 1000], ['selection.pretest_share', 0], ['rate.rescores_per_day', 100000]]
  for (const [key, value] of values) await db.owner.query(`update public.app_config set value = $2::jsonb where key = $1`, [key, JSON.stringify(value)])
}

function read(req: IncomingMessage): Promise<string> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = []
    req.on('data', (c: Buffer) => chunks.push(c))
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')))
    req.on('error', reject)
  })
}

function serve(db: TestDb, port: number): Promise<() => Promise<void>> {
  const send = (res: ServerResponse, status: number, body: unknown): void => {
    res.writeHead(status, { 'content-type': 'application/json', ...CORS })
    res.end(JSON.stringify(body))
  }
  const server = createServer((req, res) => {
    void (async () => {
      if (req.method === 'OPTIONS') {
        res.writeHead(204, CORS)
        res.end()
        return
      }
      if (req.method === 'GET' && req.url === '/ready') return send(res, 200, { ready: true })
      const m = /^\/rest\/v1\/rpc\/(\w+)$/u.exec(req.url ?? '')
      if (req.method !== 'POST' || m === null) return send(res, 404, { code: 'PGRST125', message: 'Invalid path specified in request URL', details: null, hint: null })
      const body = await read(req)
      try {
        // A person takes their time over a question; a test does not (module comment).
        if (m[1] === 'submit') await db.owner.query(`update public.exposure_log set served_at = served_at - interval '20 seconds'`)
        const data = await db.rpc({ ...ANON, headers: { 'x-forwarded-for': '198.51.100.77' } }, m[1]!, body === '' ? {} : (JSON.parse(body) as Record<string, unknown>))
        send(res, 200, data)
      } catch (e) {
        const err = e as { code?: string; message?: string; detail?: string; hint?: string }
        send(res, statusOf(err.code), { code: err.code ?? '', message: err.message ?? 'error', details: err.detail ?? null, hint: err.hint ?? null })
      }
    })().catch((e: unknown) => send(res, 500, { code: '', message: String(e), details: null, hint: null }))
  })
  return new Promise((resolve) => server.listen(port, '127.0.0.1', () => resolve(() => new Promise<void>((done) => server.close(() => done())))))
}

async function main(): Promise<void> {
  const cluster = await startCluster()
  const closers: (() => Promise<void>)[] = []
  try {
    const plain = await createTestDb(cluster)
    const text = await createTestDb(cluster)
    const passage = await createTestDb(cluster)
    const games = await createTestDb(cluster)
    const estimates = await createTestDb(cluster)
    for (const db of [plain, text, passage, games, estimates]) {
      await relax(db)
      await loadFixtureBank(db, seriesItems(12))
    }
    await loadFixtureBank(text, TEXT_PRESENT.flatMap((k) => textItems(k, TEXT_PER_AXIS, 'e2e')))
    await loadFixtureBank(passage, passageItems({ passages: PASSAGES, seed: 'e2e', attribution: passageCredit }))
    await loadFixtureBank(games, logicGameItems(GAMES, 'e2e'))
    await loadFixtureBank(estimates, [...fermiItems(FAMILY_ITEMS, 'e2e'), ...vignetteItems(FAMILY_ITEMS, 'e2e'), ...sjtItems(FAMILY_ITEMS, 'e2e'), ...ratItems(FAMILY_ITEMS, 'e2e')])
    // (the "text" port is the one the Playwright config waits for: it is opened last)
    closers.push(await serve(plain, DB_PORT), await serve(passage, DB_PORT + PASSAGE_PORT_OFFSET), await serve(games, DB_PORT + GAMES_PORT_OFFSET), await serve(estimates, DB_PORT + ESTIMATES_PORT_OFFSET), await serve(text, DB_PORT + 1))
    for (const db of [plain, text, passage, games, estimates]) closers.push(() => db.close().catch(() => undefined))
    console.error(`e2e:db: plain pool on http://127.0.0.1:${DB_PORT}, text pool on http://127.0.0.1:${DB_PORT + 1}, passage pool on http://127.0.0.1:${DB_PORT + PASSAGE_PORT_OFFSET}`)
    await new Promise<void>((resolve) => {
      for (const signal of ['SIGINT', 'SIGTERM', 'SIGHUP'] as const) process.once(signal, () => resolve())
    })
  } finally {
    for (const close of closers) await close().catch(() => undefined)
    await cluster.stop()
  }
}

await main()
process.exit(0)
